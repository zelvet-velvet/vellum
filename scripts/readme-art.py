def icon(art):
    rows = art.strip("\n").split("\n")
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), rows
    return [[ORANGE if c == "#" else SHADE if c == "+" else GREY if c == "x" else None for c in r] for r in rows]


if __name__ == "__main__":
    import os
    os.makedirs("assets/icons", exist_ok=True)
    os.makedirs("assets/icons/h", exist_ok=True)
    for name, art in ICONS.items():
        g = icon(art)
        open(f"assets/icons/{name}.svg", "w").write(svg(g, 2))
        rows = [y for y, r in enumerate(g) if any(r)]; cols = [x for x in range(16) if any(r[x] for r in g)]
        # h/: the drawing, trimmed across, centred in a box 15 pixels high: drawn as tall as a capital and sitting on the
        # baseline (no align), every icon is centred on the text the same way
        t = [r[cols[0]:cols[-1] + 1] for r in g[rows[0]:rows[-1] + 1]]
        top = (15 - len(t)) // 2; w = len(t[0])
        box = [[None] * w for _ in range(top)] + t + [[None] * w for _ in range(15 - top - len(t))]
        open(f"assets/icons/h/{name}.svg", "w").write(svg(box, 2))
    print(f"{len(ICONS)} icons")
