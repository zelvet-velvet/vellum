# the palette (ZeLedger's "Popping and Locking"): navy ground, cream, the orange accent and its shade, teal, green
NAVY, DEEP, CREAM, ORANGE, SHADE, TEAL, GREEN, DIM = "#1C1D26", "#16171F", "#F2E5BC", "#E9892B", "#B8641A", "#7DB3C9", "#A3CF7E", "#30334A"


def svg(grid, scale, bg=None, radius=0):
    """grid: rows of colours (None = empty); one rect per run of equal colours in a row"""
    h, w = len(grid), len(grid[0])
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * scale}" height="{h * scale}" viewBox="0 0 {w} {h}" shape-rendering="crispEdges">']
    if bg:
        out.append(f'<rect width="{w}" height="{h}" rx="{radius}" fill="{bg}" shape-rendering="geometricPrecision"/>')
    for y, row in enumerate(grid):
        x = 0
        while x < w:
            c = row[x]
            if c is None:
                x += 1
                continue
            n = 1
            while x + n < w and row[x + n] == c:
                n += 1
            out.append(f'<rect x="{x}" y="{y}" width="{n}" height="1" fill="{c}"/>')
            x += n
    out.append("</svg>\n")
    return "".join(out)


